pb = p;

for ih = 1:numel(hs)

    p.D = ...
        24/hs(ih);

    assert( ...
        p.D>p.W, ...
        'Permeate flow must be positive.');

    for iy = 1:numel(ys)

        p.Y = [ ...
            ys(iy); ...
            0.033; ...
            0.027; ...
            0.035];

        p.N = matrix(p);

        for ik = 1:numel(ks)

            p.k = ...
                24*ks(ik);

            for it = 1:numel(Ts)

                T = Ts(it);

                for ig = 1:numel(ygs)

                    p.yg = ygs(ig);

                    c = steady(T,p);

                    [Eh,B,mres] = ...
                        energy(c,T,p,0.35);

                    mg = ...
                        p.k ...
                        *(c(14)-eqCH4(T,p)) ...
                        /p.D;

                    mp = ...
                        (p.D-p.W) ...
                        *c(14) ...
                        /p.D;

                    mw = ...
                        p.W ...
                        *c(14) ...
                        /p.D;

                    mtotal = ...
                        mg+mp+mw;

                    liquid_phase_pct = ...
                        100*(mp+mw)/mtotal;

                    permeate_ch4_pct = ...
                        100*mp/mtotal;

                    cod_removed = ...
                        p.C0 ...
                        -sum(c(3:8));

                    assert( ...
                        cod_removed>0, ...
                        'COD removal must be positive for methane-yield diagnostic.');

                    methane_yield = ...
                        ( ...
                          mtotal ...
                          /16000 ...
                          *22.414 ...
                        ) ...
                        /(cod_removed/1000);

                    ch4_supersaturation = ...
                        c(14) ...
                        /eqCH4(T,p);

                    cres = ...
                        p.D ...
                        *(p.C0+4*p.Cin) ...
                        -exportCOD(c,T,p);

                    rr = ...
                        rhs(0,c,T,p);

                    cod_ode = ...
                        max(abs(rr(1:13)));

                    ch4_ode = ...
                        abs(rr(14));

                    n = n+1;

                    H(n,:) = [ ...
                        hs(ih), ...
                        T, ...
                        ys(iy), ...
                        ks(ik), ...
                        ygs(ig), ...
                        sum(c(3:8)), ...
                        c(14), ...
                        mg, ...
                        mp, ...
                        mw, ...
                        liquid_phase_pct, ...
                        permeate_ch4_pct, ...
                        Eh, ...
                        B, ...
                        Eh+B, ...
                        cres, ...
                        mres, ...
                        cod_ode, ...
                        ch4_ode, ...
                        methane_yield, ...
                        ch4_supersaturation];

