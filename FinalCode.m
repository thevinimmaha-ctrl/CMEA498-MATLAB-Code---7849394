% 6A. MODEL STATE VECTOR
%% =========================================================================
%
% The reactor state vector c contains 14 states:
%
%   c(1)   retained particulate biodegradable COD
%   c(2)   inert particulate COD
%   c(3)   ultrafiltrable biodegradable COD
%   c(4)   inert ultrafiltrable COD
%   c(5)   fermentable / soluble monomer substrate
%   c(6)   propionate
%   c(7)   acetate
%   c(8)   hydrogen-equivalent substrate
%   c(9)   acidogenic biomass
%   c(10)  propionate-degrading biomass
%   c(11)  acetoclastic methanogenic biomass
%   c(12)  hydrogenotrophic methanogenic biomass
%   c(13)  inert COD produced from the non-biodegradable decay fraction
%   c(14)  dissolved methane
%
% States c(1:13) are represented on an mg COD/L basis.
% State c(14) is represented separately as mg CH4/L.
%
% In the present implementation the inert particulate and inert
% ultrafiltrable influent fractions are set to zero, so c(2) and c(4)
% remain zero under the adopted source-framework feed boundary.
%
% For dynamic simulation an additional integration state z(15) is used:
%
%   z(15) = time-integrated COD export used only for numerical
%           mass-balance verification.
%
% z(15) is not a biological reactor state.
%
%% =========================================================================

%% =========================================================================
% 7. STEADY-STATE MODEL
%% =========================================================================

S = zeros( ...
    numel(ys) ...
    *numel(ks) ...
    *numel(Ts) ...
    *numel(ygs), ...
    19);

n = 0;

for iy = 1:numel(ys)

    p.Y = [ ...
        ys(iy); ...
        0.033; ...
        0.027; ...
        0.035];

    p.N = matrix(p);

    assert( ...
        max(abs(sum(p.N,1))) < 1e-10, ...
        'Stoichiometry fails COD closure.');

    for ik = 1:numel(ks)

        p.k = 24*ks(ik);

        for it = 1:numel(Ts)

            T = Ts(it);

            for ig = 1:numel(ygs)

                p.yg = ygs(ig);

                c = steady(T,p);

                [Eh,B,res] = ...
                    energy(c,T,p,0.35);

                mg = ...
                    p.k ...
                    *(c(14)-eqCH4(T,p)) ...
                    /p.D;

                mp = ...
                    (p.D-p.W) ...
                    *c(14) ...
                    /p.D;

                mw = ...
                    p.W ...
                    *c(14) ...
                    /p.D;

                mtotal = mg + mp + mw;

                liquid_phase_pct = ...
                    100*(mp+mw)/mtotal;

                permeate_ch4_pct = ...
                    100*mp/mtotal;

                cod_removed = ...
                    p.C0 ...
                    -sum(c(3:8));

                assert( ...
                    cod_removed>0, ...
                    'COD removal must be positive for methane-yield diagnostic.');

                methane_yield = ...
                    ( ...
                      mtotal ...
                      /16000 ...
                      *22.414 ...
                    ) ...
                    /(cod_removed/1000);

                ch4_supersaturation = ...
                    c(14) ...
                    /eqCH4(T,p);

                rr = rhs(0,c,T,p);

                cod_ode = ...
                    max(abs(rr(1:13)));

                ch4_ode = ...
                    abs(rr(14));

                n = n+1;

                S(n,:) = [ ...
                    T, ...
                    ys(iy), ...
                    ks(ik), ...
                    ygs(ig), ...
                    sum(c(3:8)), ...
                    c(14), ...
                    mg, ...
                    mp, ...
                    mw, ...
                    liquid_phase_pct, ...
                    permeate_ch4_pct, ...
                    Eh, ...
                    B, ...
                    Eh+B, ...
                    res, ...
                    cod_ode, ...
                    ch4_ode, ...
                    methane_yield, ...
                    ch4_supersaturation];

            end
        end
    end
end

