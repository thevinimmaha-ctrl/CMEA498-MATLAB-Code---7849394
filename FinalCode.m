N(6,3) = ...
    14/24 ...
    *(1/Y(1)-1);

N(7,3) = ...
    8/24 ...
    *(1/Y(1)-1);

N(8,3) = ...
    2/24 ...
    *(1/Y(1)-1);

N(9,3) = 1;

N(6,4) = -1/Y(2);

N(7,4) = ...
    8/14 ...
    *(1/Y(2)-1);

