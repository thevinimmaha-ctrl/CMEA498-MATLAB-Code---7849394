function [kh,mu,b] = ratesT(T,p)

f = ...
    1.07^(T-20);

kh = ...
    p.kh*f;

mu = ...
    p.mu*f;

b = ...
    p.b*f;

end

function v = rates(c,T,p)

[kh,mu,b] = ...
    ratesT(T,p);

v = [ ...
    kh.*c([1,3]); ...
    mu.*c(5:8) ...
    ./(p.K+c(5:8)) ...
    .*c(9:12); ...
    b.*c(9:12)];

end

function v = book(c,T,p)

loss = ...
    p.D ...
    *ones(14,1);

loss([1,2,9:13]) = ...
    p.W;

in = ...
    zeros(14,1);

in(1) = ...
    p.D ...
    *p.C0 ...
    *(1-p.uf);

in(3) = ...
    p.D ...
    *p.C0 ...
    *p.uf;

v = ...
    in ...
    -loss.*c ...
    +p.N*rates(c,T,p);

end

function c = steady(T,p)

[kh,mu,b] = ...
    ratesT(T,p);

assert( ...
    all(mu>p.W+b), ...
    'Positive biomass branch unavailable; check washout.');

c = ...
    zeros(14,1);

c(3) = ...
    p.D ...
    *p.C0 ...
    *p.uf ...
    /(p.D+kh(2));

c(5:8) = ...
    p.K ...
    .*(p.W+b) ...
    ./(mu-p.W-b);

ix = ...
    [1,9:14];

eq = ...
    [1,5:8,13,14];

v = ...
    book(c,T,p);

A = ...
    zeros(7);

for j = 1:7

    x = c;

    x(ix(j)) = ...
        x(ix(j))+1;

    u = ...
        book(x,T,p);

    A(:,j) = ...
        u(eq)-v(eq);

end

c(ix) = ...
    A\(-v(eq));

assert( ...
    min(c)>-1e-8, ...
    'Nonphysical biological steady state.');

assert( ...
    max(abs(book(c,T,p)))<1e-7, ...
    'Biological steady-state check failed.');

Rbio = ...
    p.N(14,:) ...
    *rates(c,T,p);

c(14) = ...
    ( ...
      p.D*p.Cin ...
      +Rbio/4 ...
      +p.k*eqCH4(T,p) ...
    ) ...
    /(p.D+p.k);

end

function q = eqCH4(T,p)

q = ...
    p.H ...
    *exp( ...
        p.aH ...
        *( ...
          1/(T+273.15) ...
          -1/298.15 ...
         ) ...
        ) ...
    *p.yg ...
    *p.Pg ...
    *16000;

end

function v = rhs(~,c,T,p)

a = ...
    rates(c,T,p);

v = ...
    book(c,T,p);

Rbio = ...
    p.N(14,:) ...
    *a;

v(14) = ...
    p.D ...
    *(p.Cin-c(14)) ...
    +Rbio/4 ...
    -p.k ...
    *(c(14)-eqCH4(T,p));

end

function out = exportCOD(c,T,p)

out = ...
    p.W ...
    *sum(c([1,2,9:13])) ...
    +p.D ...
    *sum(c(3:8)) ...
    +4*p.D*c(14) ...
    +4*p.k ...
    *(c(14)-eqCH4(T,p));

end

function v = dynamic(t,z,T,p)

c = ...
    z(1:14);

v = [ ...
    rhs(t,c,T,p); ...
    exportCOD(c,T,p)];

end

function [value,terminal,direction] = stop(~,z,target)

value = ...
    max( ...
        abs(z(1:14)-target) ...
        ./max(abs(target),1) ...
       ) ...
    -1e-5;

terminal = 1;

direction = -1;

end

function [Eh,B,res] = energy(c,T,p,eta)

Rbio = ...
    p.N(14,:) ...
    *rates(c,T,p) ...
    /4;

G = ...
    p.k ...
    *(c(14)-eqCH4(T,p));

assert( ...
    G>=0, ...
    'Gas absorption: produced-fuel credit not applicable.');

mp = ...
    (p.D-p.W) ...
    /p.D ...
    *c(14);

mg = ...
    G/p.D;

mw = ...
    p.W ...
    /p.D ...
    *c(14);

res = ...
    Rbio/p.D ...
    +p.Cin ...
    -mg ...
    -mp ...
    -mw;

Eh = ...
    eta ...
    *p.h/3.6 ...
    *0.001 ...
    *mg;

B = ...
    eta ...
    *p.h/3.6 ...
    *0.001 ...
    *mp;

end

function t5 = settle(t,y,y0,yf)

d = ...
    abs(yf-y0);

if d<1e-10

    t5 = NaN;

    return;

end

err = ...
    abs(y-yf);

band = ...
    0.05*d;

j = ...
    find( ...
        err>band, ...
        1, ...
        'last');

if isempty(j)

    t5 = 0;

elseif j==numel(t)

    t5 = NaN;

else

    a = ...
        (err(j)-band) ...
        /(err(j)-err(j+1));

    t5 = ...
        t(j) ...
        +a ...
        *(t(j+1)-t(j));

end

end

function t5 = settleMethane(t,y,y0,yf)

d = ...
    abs(yf-y0);

scale = ...
    abs(yf);

if scale<1e-10 ...
        || d<=0.05*scale

    t5 = NaN;

    return;

end

err = ...
    abs(y-yf);

band = ...
    0.05*d;

j = ...
    find( ...
        err>band, ...
        1, ...
        'last');

if isempty(j)

    t5 = 0;

elseif j==numel(t)

    t5 = NaN;

else

    a = ...
        (err(j)-band) ...
        /(err(j)-err(j+1));

    t5 = ...
        t(j) ...
        +a ...
        *(t(j+1)-t(j));

end

end

function ov = overshoot(y,y0,yf)

if yf>=y0

    ov = ...
        max( ...
            0, ...
            max(y)-yf);

else

    ov = ...
        max( ...
            0, ...
            yf-min(y));

end

