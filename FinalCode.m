% 11. DYNAMIC TEMPERATURE-STEP TESTS
%% =========================================================================

F = struct([]);
V = [];

n = 0;

targets = [15,25];

for jt = 1:numel(targets)

    T = targets(jt);

    for iy = 1:numel(ys)

        p.Y = [ ...
            ys(iy); ...
            0.033; ...
            0.027; ...
            0.035];

        p.N = matrix(p);

        for ik = 1:numel(ks)

            p.k = 24*ks(ik);

            c0 = steady(20,p);
            ct = steady(T,p);

            z0 = [c0;0];

            M0 = ...
                sum(c0(1:13)) ...
                +4*c0(14);

            opt = odeset( ...
                'RelTol',1e-8, ...
                'AbsTol',1e-9, ...
                'Events', ...
                @(t,z) stop(t,z,ct));

            sol = ode15s( ...
                @(t,z) dynamic(t,z,T,p), ...
                [0,1000], ...
                z0, ...
                opt);

            assert( ...
                isfield(sol,'xe') ...
                && ~isempty(sol.xe), ...
                'Did not reach strict numerical convergence.');

            tf = sol.x(end);

            t = [ ...
                0, ...
                logspace( ...
                    -6, ...
                    log10(tf), ...
                    12000) ...
                ]';

            t = unique(min(t,tf));

            z = deval(sol,t')';

            assert( ...
                min(min(z(:,1:14))) > -1e-7, ...
                'Negative state detected.');

            M = ...
                sum(z(:,1:13),2) ...
                +4*z(:,14);

            bal = ...
                M ...
                -M0 ...
                -p.D*(p.C0+4*p.Cin)*t ...
                +z(:,15);

            assert( ...
                max(abs(bal)) < 1e-4, ...
                'Integrated COD balance failed.');

            cod = ...
                sum(z(:,3:8),2);

            ch = ...
                z(:,14);

            cf = ...
                sum(ct(3:8));

            mf = ...
                ct(14);

            tc = ...
                settle( ...
                    t, ...
                    cod, ...
                    cod(1), ...
                    cf);

            tm = ...
                settleMethane( ...
                    t, ...
                    ch, ...
                    ch(1), ...
                    mf);

            tt = [ ...
                0, ...
                logspace( ...
                    -6, ...
                    log10(tf), ...
                    24000) ...
                ]';

            tt = unique(min(tt,tf));

            zz = ...
                deval(sol,tt')';

            tc2 = ...
                settle( ...
                    tt, ...
                    sum(zz(:,3:8),2), ...
                    cod(1), ...
                    cf);

            tm2 = ...
                settleMethane( ...
                    tt, ...
                    zz(:,14), ...
                    ch(1), ...
                    mf);

            if isnan(tm) && isnan(tm2)

                methane_grid_ok = true;

            else

                methane_grid_ok = ...
                    ~isnan(tm) ...
                    && ~isnan(tm2) ...
                    && abs(tm-tm2)<0.1;

            end

            assert( ...
                abs(tc-tc2)<0.1 ...
                && methane_grid_ok, ...
                'Response-time grid needs refinement.');

            cod_ov = ...
                overshoot( ...
                    cod, ...
                    cod(1), ...
                    cf);

            % Dissolved-methane transient diagnostics.

            ch_initial = ch(1);
            ch_final = mf;

            [ch_max,i_ch_max] = max(ch);
            [ch_min,i_ch_min] = min(ch);

            t_ch_max = t(i_ch_max);
            t_ch_min = t(i_ch_min);

            ch_upper_endpoint = ...
                max(ch_initial,ch_final);

            ch_lower_endpoint = ...
                min(ch_initial,ch_final);

            % Monotonic initial-to-final responses have zero overshoot/undershoot.

            ch_overshoot = ...
                max( ...
                    0, ...
                    ch_max-ch_upper_endpoint);

            ch_undershoot = ...
                max( ...
                    0, ...
                    ch_lower_endpoint-ch_min);

            % Excursions are expressed relative to the final steady-state DCH4.

            if abs(ch_final) > 1e-12

                ch_overshoot_pct = ...
                    100 ...
                    *ch_overshoot ...
                    /abs(ch_final);

                ch_undershoot_pct = ...
                    100 ...
                    *ch_undershoot ...
                    /abs(ch_final);

            else

                ch_overshoot_pct = NaN;
                ch_undershoot_pct = NaN;

            end

            assert( ...
                ch_overshoot >= -1e-12, ...
                'Negative methane overshoot detected.');

            assert( ...
                ch_undershoot >= -1e-12, ...
                'Negative methane undershoot detected.');

            n = n+1;

            F(n).T = T;
            F(n).ya = ys(iy);
            F(n).k = ks(ik);
            F(n).t = t;
            F(n).cod = cod;
            F(n).ch = ch;
            F(n).cf = cf;
            F(n).mf = mf;
            F(n).tc = tc;
            F(n).tm = tm;

            F(n).CH4_initial = ch_initial;
            F(n).CH4_final = ch_final;
            F(n).CH4_max = ch_max;
            F(n).CH4_min = ch_min;
            F(n).CH4_tmax_d = t_ch_max;
            F(n).CH4_tmin_d = t_ch_min;
            F(n).CH4_overshoot = ch_overshoot;
            F(n).CH4_undershoot = ch_undershoot;
            F(n).CH4_overshoot_pct = ch_overshoot_pct;
            F(n).CH4_undershoot_pct = ch_undershoot_pct;

            V(n,:) = [ ...
                T, ...
                ys(iy), ...
                ks(ik), ...
                tc, ...
                tm, ...
                cod_ov, ...
                ch_initial, ...
                ch_final, ...
